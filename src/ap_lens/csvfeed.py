"""The pilot path: a client's daily CSV export (docs/feed_spec.md) -> AP-Lens's event log.

Four files: po_lines, gr_lines, invoice_lines, outcomes. Each PO line becomes a case; receipts,
invoices and AP's actions become events with quantity and unit price, so the 3-way match can
run per line and say whether the price or the quantity is off.

`sample()` writes a synthetic feed in the same format for testing the path end to end. Its
labels are generated by rules I wrote, so it tests plumbing, never accuracy.
"""
from __future__ import annotations

import os
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

import pandas as pd

from . import config as C

FEED_DIR = Path(os.environ.get("APLENS_FEED_DIR", C.DATA / "feed"))

REQUIRED = {
    "po_lines.csv": ["po_id", "po_line", "created_at", "created_by", "vendor_id", "qty", "unit_price", "currency"],
    "gr_lines.csv": ["po_id", "po_line", "gr_id", "posted_at", "posted_by", "qty"],
    "invoice_lines.csv": ["po_id", "po_line", "invoice_id", "received_at", "recorded_by", "qty", "unit_price"],
    "outcomes.csv": ["po_id", "po_line", "at", "by", "action"],
}
OUTCOME_ACTIVITY = {"RELEASE": C.UNBLOCK, "FIX_PRICE": C.CHG_PRICE, "FIX_QTY": C.CHG_QTY, "CANCEL": C.CANCEL_INV}
TIE_ORDER = {C.CREATE: 0, C.GR: 1, C.CANCEL_GR: 2, C.INV: 3, C.CHG_PRICE: 4, C.CHG_QTY: 5,
             C.UNBLOCK: 6, C.CANCEL_INV: 7}


class FeedError(ValueError):
    pass


def read(feed_dir: Path = FEED_DIR) -> dict[str, pd.DataFrame]:
    frames = {}
    for name, cols in REQUIRED.items():
        p = feed_dir / name
        if not p.exists():
            if name == "outcomes.csv":  # live mode can run without history
                frames[name] = pd.DataFrame(columns=cols)
                continue
            raise FeedError(f"missing {p}")
        df = pd.read_csv(p, dtype={"po_id": str, "po_line": str})
        missing = [c for c in cols if c not in df.columns]
        if missing:
            raise FeedError(f"{name} is missing required columns: {', '.join(missing)}")
        frames[name] = df
    bad = set(frames["outcomes.csv"]["action"].dropna()) - set(OUTCOME_ACTIVITY)
    if bad:
        raise FeedError(f"outcomes.csv has unknown actions: {sorted(bad)}")
    return frames


def _ts(x) -> pd.Timestamp:
    return pd.Timestamp(x, tz="UTC") if pd.Timestamp(x).tzinfo is None else pd.Timestamp(x).tz_convert("UTC")


def _truthy(x) -> bool:
    return str(x).strip().lower() in ("true", "1", "yes", "y")


def to_events(f: dict[str, pd.DataFrame]) -> tuple[pd.DataFrame, pd.DataFrame]:
    po, gr, inv, out = f["po_lines.csv"], f["gr_lines.csv"], f["invoice_lines.csv"], f["outcomes.csv"]
    key = lambda r: f"{r['po_id']}-{r['po_line']}"
    po_price = {key(r): float(r["unit_price"]) for _, r in po.iterrows()}
    rows = []

    def add(r, act, ts, res, qty=None, price=None):
        q = None if qty is None or pd.isna(qty) else float(qty)
        p = None if price is None or pd.isna(price) else float(price)
        rows.append({C.CASE: key(r), C.ACT: act, C.TS: _ts(ts), C.RES: str(res), "qty": q, "unit_price": p,
                     C.VALUE: None if q is None or p is None else q * p})

    for _, r in po.iterrows():
        add(r, C.CREATE, r["created_at"], r["created_by"], r["qty"], r["unit_price"])
    for _, r in gr.iterrows():
        act = C.CANCEL_GR if _truthy(r.get("cancelled", False)) else C.GR
        add(r, act, r["posted_at"], r["posted_by"], r["qty"], po_price.get(key(r)))
    for _, r in inv.iterrows():
        act = C.CANCEL_INV if _truthy(r.get("cancelled", False)) else C.INV
        add(r, act, r["received_at"], r["recorded_by"], r["qty"], r["unit_price"])
    for _, r in out.iterrows():
        a = r["action"]
        add(r, OUTCOME_ACTIVITY[a], r["at"], r["by"],
            r.get("new_qty") if a == "FIX_QTY" else None,
            r.get("new_unit_price") if a == "FIX_PRICE" else None)
    ev = pd.DataFrame(rows)
    ev["_tie"] = ev[C.ACT].map(TIE_ORDER).fillna(9)
    ev = ev.sort_values([C.CASE, C.TS, "_tie"]).drop(columns="_tie").reset_index(drop=True)
    ev["seq"] = ev.groupby(C.CASE).cumcount()
    orphan = set(ev[C.CASE]) - set(po.apply(key, axis=1))
    if orphan:
        raise FeedError(f"{len(orphan)} receipt/invoice/outcome rows point to PO lines not in po_lines.csv, "
                        f"e.g. {sorted(orphan)[:3]}")
    cs = pd.DataFrame({
        C.CASE: po.apply(key, axis=1), C.ITEM_CATEGORY: C.BLOCK_FLOW,
        "vendor": po["vendor_id"].astype(str),
        "item_type": po.get("item_type"), "spend_area_text": po.get("spend_area"),
        "sub_spend_area_text": None, "document_type": po.get("document_type"),
        "company": po.get("company"), "currency": po["currency"],
    })
    return ev, cs


def build(feed_dir: Path = FEED_DIR) -> dict:
    ev, cs = to_events(read(feed_dir))
    ev.to_parquet(C.parquet("events"), index=False)
    cs.to_parquet(C.parquet("cases"), index=False)
    from .load import inventory
    inv = inventory(ev, cs)
    inv["feed_dir"] = str(feed_dir)
    return inv


# ---------------------------------------------------------------- sample feed
SCENARIOS = [  # name, weight
    ("clean_after_goods", 0.48), ("invoice_before_goods", 0.24), ("price_mismatch", 0.11),
    ("quantity_mismatch", 0.08), ("duplicate_invoice", 0.04), ("released_despite_small_diff", 0.05),
]


def sample(out_dir: Path = FEED_DIR, n: int = 2500, seed: int = C.SEED) -> Path:
    """Synthetic feed in the spec's format. Plumbing test only: labels follow my own rules."""
    rng = random.Random(seed)
    out_dir.mkdir(parents=True, exist_ok=True)
    t0 = datetime(2026, 1, 5, 8, tzinfo=timezone.utc)
    po, gr, inv, out = [], [], [], []
    user = lambda: f"user_{rng.randint(1, 25):02d}"
    for k in range(n):
        po_id, line = f"45{k:08d}", "10"
        base = dict(po_id=po_id, po_line=line)
        t = t0 + timedelta(hours=rng.uniform(0, 24 * 300))
        qty = rng.choice([1, 2, 5, 10, 20, 40, 100])
        price = round(rng.lognormvariate(3, 1), 2)
        po.append({**base, "created_at": t.isoformat(), "created_by": rng.choice([user(), "batch_po"]),
                   "vendor_id": f"V-{rng.randint(1, 180):05d}", "qty": qty, "unit_price": price, "currency": "EUR",
                   "item_type": rng.choice(["Standard", "Service", "Subcontracting"]),
                   "spend_area": rng.choice(["Packaging", "Logistics", "Labs", "Sales", "CAPEX"]),
                   "document_type": rng.choice(["Standard PO", "Framework order"]),
                   "company": rng.choice(["C100", "C200", "C300"])})
        scen = rng.choices([s for s, _ in SCENARIOS], weights=[w for _, w in SCENARIOS])[0]
        if scen == "quantity_mismatch" and qty < 5:  # a partial delivery needs more than a unit or two
            qty = rng.choice([10, 20, 40, 100])
            po[-1]["qty"] = qty
        later = lambda days: t + timedelta(days=days, hours=rng.uniform(0, 8))
        d_gr, d_inv = rng.uniform(2, 15), rng.uniform(2, 15)
        if scen == "invoice_before_goods":
            d_inv, d_gr = rng.uniform(1, 5), rng.uniform(6, 20)
        inv_qty, inv_price, recv_qty = qty, price, qty
        if scen == "price_mismatch":
            inv_price = round(price * rng.uniform(1.05, 1.25), 2)
        elif scen == "quantity_mismatch":
            recv_qty = max(1, int(qty * rng.uniform(0.5, 0.9)))
        elif scen == "released_despite_small_diff":
            inv_price = round(price * 1.03, 2)
        gr.append({**base, "gr_id": f"50{k:08d}", "posted_at": later(d_gr).isoformat(), "posted_by": user(),
                   "qty": recv_qty, "cancelled": False})
        inv.append({**base, "invoice_id": f"51{k:08d}", "received_at": later(d_inv).isoformat(),
                    "recorded_by": user(), "qty": inv_qty, "unit_price": inv_price, "cancelled": False})
        decide_at = later(max(d_gr, d_inv) + rng.uniform(0.5, 6))
        who = user() if scen != "clean_after_goods" or rng.random() < 0.3 else "batch_rel"
        if scen == "price_mismatch":
            out.append({**base, "at": decide_at.isoformat(), "by": user(), "action": "FIX_PRICE",
                        "new_unit_price": inv_price, "new_qty": None})
            out.append({**base, "at": later(max(d_gr, d_inv) + 8).isoformat(), "by": user(), "action": "RELEASE",
                        "new_unit_price": None, "new_qty": None})
        elif scen == "quantity_mismatch":
            out.append({**base, "at": decide_at.isoformat(), "by": user(), "action": "FIX_QTY",
                        "new_unit_price": None, "new_qty": recv_qty})
        elif scen == "duplicate_invoice":
            out.append({**base, "at": decide_at.isoformat(), "by": user(), "action": "CANCEL",
                        "new_unit_price": None, "new_qty": None})
        else:
            out.append({**base, "at": decide_at.isoformat(), "by": who, "action": "RELEASE",
                        "new_unit_price": None, "new_qty": None})
    for name, rows in (("po_lines.csv", po), ("gr_lines.csv", gr), ("invoice_lines.csv", inv), ("outcomes.csv", out)):
        pd.DataFrame(rows).to_csv(out_dir / name, index=False)
    (out_dir / "SYNTHETIC.txt").write_text("Synthetic sample feed generated by ap_lens.csvfeed.sample(). "
                                           "For testing the pilot path only; never report its numbers.\n")
    return out_dir
